/** 槽位树之外的模块(挂载/RPC 包装层)用的绑定翻译。 */
let bound: Translate | undefined

/** locale.bind(NS) 之后由插件体调用,使非槽位模块拿到随 locale 切换的 t。 */
export function setBoundT(t: Translate): void {
  bound = t
}

/** 模块级翻译:未绑定(宿主未注入 locale)时回退键名本身。 */
export function tr(key: string, params?: Record<string, unknown>): string {
  return bound !== undefined ? bound(key, params) : key
}
